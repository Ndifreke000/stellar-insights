#!/usr/bin/env node
// Regenerate the release matrix in sdk/COMPATIBILITY.md.
//
// Source of truth is sdk/compatibility.json (newest row first). On each run
// the current package / contract versions are read from the repo; if they
// differ from the newest row, a new row dated today (UTC) is prepended. The
// markdown table between the compat-matrix markers is then re-rendered.
//
// Runs automatically in `npm run version-packages`, so the "Version Packages"
// PR opened by the release workflow always carries the updated matrix.
//
//   node scripts/release/update-compatibility.mjs           # update files
//   node scripts/release/update-compatibility.mjs --check   # exit 1 if stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const sdkDir = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const repoDir = join(sdkDir, "..");
const dataPath = join(sdkDir, "compatibility.json");
const docPath = join(sdkDir, "COMPATIBILITY.md");
const START = "<!-- compat-matrix:start (generated by sdk/scripts/release/update-compatibility.mjs; edit sdk/compatibility.json instead) -->";
const END = "<!-- compat-matrix:end -->";

const COLUMNS = [
  ["date", "Released"],
  ["sdk", "`@payraider/sdk`"],
  ["react", "`@payraider/react`"],
  ["mcpServer", "`@payraider/mcp-server`"],
  ["python", "`payraider` (PyPI)"],
  ["contract", "`payraider` contract"],
  ["sorobanSdk", "`soroban-sdk`"],
  ["api", "REST API"],
  ["networks", "Networks"],
];
// Fields that identify a release; `date`, `networks` and `notes` do not.
const VERSION_KEYS = ["sdk", "react", "mcpServer", "python", "contract", "sorobanSdk", "api"];

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const tomlValue = (path, pattern) => {
  const match = readFileSync(path, "utf8").match(pattern);
  if (!match) throw new Error(`could not find ${pattern} in ${path}`);
  return match[1];
};

function currentVersions() {
  return {
    sdk: readJson(join(sdkDir, "typescript", "package.json")).version,
    react: readJson(join(sdkDir, "react", "package.json")).version,
    mcpServer: readJson(join(sdkDir, "mcp-server", "package.json")).version,
    python: tomlValue(join(sdkDir, "python", "pyproject.toml"), /\[project\][^[]*?^version\s*=\s*"([^"]+)"/ms),
    contract: tomlValue(join(repoDir, "contracts", "payraider", "Cargo.toml"), /\[package\][^[]*?^version\s*=\s*"([^"]+)"/ms),
    sorobanSdk: tomlValue(join(repoDir, "contracts", "Cargo.toml"), /^soroban-sdk\s*=\s*(?:\{[^}]*version\s*=\s*)?"([^"]+)"/m),
    api: "v1",
  };
}

const sameVersions = (a, b) => VERSION_KEYS.every((k) => a?.[k] === b?.[k]);

function render(rows) {
  const header = `| ${COLUMNS.map(([, title]) => title).join(" | ")} |`;
  const divider = `|${COLUMNS.map(() => "---").join("|")}|`;
  const body = rows.map((row) => `| ${COLUMNS.map(([key]) => row[key] ?? "").join(" | ")} |`);
  const notes = rows
    .filter((row) => row.notes)
    .map((row) => `- **${row.date}** — ${row.notes}`);
  return [START, header, divider, ...body, ...(notes.length ? ["", ...notes] : []), END].join("\n");
}

const check = process.argv.includes("--check");
const data = readJson(dataPath);
const current = currentVersions();
let rows = data.releases;

if (!sameVersions(rows[0], current)) {
  if (check) {
    console.error("compatibility.json is behind the package versions. Run: npm run version-packages (or node scripts/release/update-compatibility.mjs)");
    console.error({ newest: rows[0], current });
    process.exit(1);
  }
  const today = new Date().toISOString().slice(0, 10);
  rows = [{ date: today, ...current, networks: rows[0]?.networks ?? "testnet, mainnet" }, ...rows];
  writeFileSync(dataPath, `${JSON.stringify({ ...data, releases: rows }, null, 2)}\n`);
  console.log(`update-compatibility: added row for ${today}`);
}

const doc = readFileSync(docPath, "utf8");
const startIdx = doc.indexOf(START);
const endIdx = doc.indexOf(END);
if (startIdx === -1 || endIdx === -1) {
  console.error(`update-compatibility: markers not found in ${docPath}`);
  process.exit(1);
}
const next = doc.slice(0, startIdx) + render(rows) + doc.slice(endIdx + END.length);

if (next !== doc) {
  if (check) {
    console.error("COMPATIBILITY.md matrix is out of date. Run: node scripts/release/update-compatibility.mjs");
    process.exit(1);
  }
  writeFileSync(docPath, next);
  console.log("update-compatibility: COMPATIBILITY.md updated");
} else {
  console.log("update-compatibility: COMPATIBILITY.md is up to date");
}
